#!/usr/bin/env python3
"""Convert every Sigma rule in frameworks/*/sigma/ and behaviors/sigma/ to Cortex XDR XQL.

Uses the community pySigma Cortex XDR backend. The queries run in Cortex XDR or XSIAM Query Builder (XQL)
and can be saved as BIOC or correlation rules.

The backend needs pySigma 0.11, which conflicts with tools/requirements.txt (pySigma 1.x and later).
Install it in its own virtual environment:

    python3 -m venv .venv-cortex
    .venv-cortex/bin/pip install -r tools/requirements-cortex.txt
    .venv-cortex/bin/python tools/convert_cortex.py

Output: generated/cortex_xdr/<framework or behaviors>/<category>/<rule>.txt and generated/cortex_xdr/SUMMARY.md.

What converts: process_creation, file_event and registry_set rules. What does not: dns_query (the backend
has no DNS mapping), proxy and web server rules, cloud log rules and correlations. Those are marked with a
dash in SUMMARY.md.

One change to the backend: it maps Sigma's TargetFilename to action_file_name, the file's base name, but the
rules here match full paths (*/.guardian/.env). This tool maps it to action_file_path instead, which also
matches base-name suffixes.

The queries are converted, not tested against Cortex XDR telemetry. Run them as hunts before you turn them
into BIOC rules.
"""
import copy
import shutil
import sys
from pathlib import Path

from sigma.collection import SigmaCollection
from sigma.correlations import SigmaCorrelationRule
from sigma.processing.conditions import RuleProcessingItemAppliedCondition
from sigma.processing.pipeline import ProcessingItem, ProcessingPipeline
from sigma.processing.transformations import FieldMappingTransformation

ROOT = Path(__file__).resolve().parent.parent
SIGMA_DIRS = sorted(ROOT.glob("frameworks/*/sigma")) + [ROOT / "behaviors" / "sigma"]
OUT = ROOT / "generated" / "cortex_xdr"


def rel_of(path):
    """frameworks/artex/sigma/web/x.yml -> artex/web/x.yml, behaviors/sigma/web/x.yml -> behaviors/web/x.yml"""
    for d in SIGMA_DIRS:
        if d in path.parents:
            return Path(d.parent.name) / path.relative_to(d)
    raise ValueError(path)


def file_path_fix():
    """Runs after the backend's own pipeline: full paths belong in action_file_path.

    The backend replaces each rule's log source with service: cortex, so a category condition would never
    match here. Key off the backend's own file field mapping step instead."""
    return ProcessingPipeline(name="Cortex XDR file paths", priority=60, items=[
        ProcessingItem(identifier="cortex_file_path",
                       transformation=FieldMappingTransformation({"action_file_name": "action_file_path"}),
                       rule_conditions=[RuleProcessingItemAppliedCondition("cortex_file_fieldmapping")])])


def reason(exc):
    text = str(exc).split("\n")[0]
    if "not yet supported" in text:
        return "log source not supported"
    if "only supports the following fields" in text or "field name" in text:
        return "field not in Cortex XDR telemetry"
    return f"{type(exc).__name__}: {text[:80]}"


def main():
    from sigma.backends.cortexxdr import CortexXDRBackend
    files = sorted(p for d in SIGMA_DIRS for p in d.rglob("*.yml"))
    base = SigmaCollection.load_ruleset([str(p) for p in files])
    if OUT.exists():
        shutil.rmtree(OUT)
    results = {}
    for rule in base.rules:
        rel = rel_of(Path(str(rule.source.path))).as_posix()
        if isinstance(rule, SigmaCorrelationRule):
            results[rel] = "- (correlation)"
            continue
        try:
            out = CortexXDRBackend(processing_pipeline=file_path_fix()).convert(SigmaCollection([copy.deepcopy(rule)]))
        except Exception as exc:  # noqa: BLE001 - report it in SUMMARY.md
            results[rel] = f"- ({reason(exc)})"
            continue
        dest = OUT / Path(rel).with_suffix(".txt")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(f"// {rule.title}\n// Sigma id {rule.id}, level {rule.level}\n" + "\n".join(map(str, out)) + "\n",
                        encoding="utf-8")
        results[rel] = "yes"
    lines = ["# Cortex XDR conversion summary", "",
             "Generated by `tools/convert_cortex.py` with the community pySigma Cortex XDR backend. The queries are XQL for "
             "Cortex XDR or XSIAM. A dash means the rule did not convert, with the reason. Sigma's `TargetFilename` is mapped to "
             "`action_file_path`, not the backend's `action_file_name`.", "",
             "The queries have not been tested against Cortex XDR telemetry. Run them as hunts before you turn them into BIOC rules.", "",
             "| Rule | xql |", "|---|---|"]
    for rel in sorted(results):
        lines.append(f"| `{rel}` | {results[rel]} |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    ok = sum(1 for v in results.values() if v == "yes")
    print(f"xql: {ok} of {len(results)} rules converted, written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
