#!/usr/bin/env python3
"""Convert every Sigma rule in frameworks/*/sigma/ and behaviors/sigma/ to SentinelOne queries.

Two query languages, from the community pySigma SentinelOne backends:
    s1ql        Deep Visibility S1QL 1.0, for Deep Visibility searches and STAR custom rules
    powerquery  Singularity Data Lake / Event Search PowerQuery

These backends need pySigma 0.11, which conflicts with tools/requirements.txt (pySigma 1.x and later).
Install them in their own virtual environment:

    python3 -m venv .venv-s1
    .venv-s1/bin/pip install -r tools/requirements-sentinelone.txt
    .venv-s1/bin/python tools/convert_sentinelone.py

Output: generated/sentinelone/<language>/<framework or behaviors>/<category>/<rule>.txt and
generated/sentinelone/SUMMARY.md.

What converts: endpoint rules (process_creation, file_event, registry_set, dns_query). What does not:
proxy and web server rules (no matching SentinelOne telemetry), cloud log rules and correlations. Those
are marked with a dash in SUMMARY.md. Use the Suricata, Zeek, WAF or SIEM versions for them.

The queries are converted, not tested against SentinelOne telemetry. Run them as hunts before you turn
them into STAR rules.
"""
import copy
import shutil
import sys
from pathlib import Path

from sigma.collection import SigmaCollection
from sigma.correlations import SigmaCorrelationRule

ROOT = Path(__file__).resolve().parent.parent
SIGMA_DIRS = sorted(ROOT.glob("frameworks/*/sigma")) + [ROOT / "behaviors" / "sigma"]
OUT = ROOT / "generated" / "sentinelone"


def rel_of(path):
    """frameworks/artex/sigma/web/x.yml -> artex/web/x.yml, behaviors/sigma/web/x.yml -> behaviors/web/x.yml"""
    for d in SIGMA_DIRS:
        if d in path.parents:
            return Path(d.parent.name) / path.relative_to(d)
    raise ValueError(path)


def targets():
    from sigma.backends.sentinelone import SentinelOneBackend
    from sigma.backends.sentinelone_pq import SentinelOnePQBackend
    return {"s1ql": SentinelOneBackend, "powerquery": SentinelOnePQBackend}


def reason(exc):
    text = str(exc).split("\n")[0]
    if "field name encountered" in text:
        return "field not in SentinelOne telemetry"
    if "not yet supported" in text or "not supported" in text:
        return "log source not supported"
    return f"{type(exc).__name__}: {text[:80]}"


def main():
    files = sorted(p for d in SIGMA_DIRS for p in d.rglob("*.yml"))
    base = SigmaCollection.load_ruleset([str(p) for p in files])
    backends = targets()
    if OUT.exists():
        shutil.rmtree(OUT)
    results = {}
    for rule in base.rules:
        rel = rel_of(Path(str(rule.source.path)))
        row = results.setdefault(rel.as_posix(), {})
        if isinstance(rule, SigmaCorrelationRule):
            for name in backends:
                row[name] = "- (correlation)"
            continue
        for name, cls in backends.items():
            try:
                # A pipeline rewrites field names on the rule objects it is given, so every backend gets its own copy.
                out = cls().convert(SigmaCollection([copy.deepcopy(rule)]))
            except Exception as exc:  # noqa: BLE001 - report it in SUMMARY.md
                row[name] = f"- ({reason(exc)})"
                continue
            dest = OUT / name / rel.with_suffix(".txt")
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(f"# {rule.title}\n# Sigma id {rule.id}, level {rule.level}\n" + "\n".join(map(str, out)) + "\n",
                            encoding="utf-8")
            row[name] = "yes"
    names = list(backends)
    lines = ["# SentinelOne conversion summary", "",
             "Generated by `tools/convert_sentinelone.py` with the community pySigma SentinelOne backends. "
             "`s1ql` is Deep Visibility S1QL 1.0 (Deep Visibility and STAR custom rules), `powerquery` is the Singularity Data Lake "
             "PowerQuery. A dash means the rule did not convert, with the reason.", "",
             "The queries have not been tested against SentinelOne telemetry. Run them as hunts before you turn them into STAR rules.", "",
             "| Rule | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for rel in sorted(results):
        lines.append(f"| `{rel}` | " + " | ".join(results[rel][n] for n in names) + " |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for n in names:
        ok = sum(1 for r in results.values() if r[n] == "yes")
        print(f"{n}: {ok} of {len(results)} rules converted")
    print(f"written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
